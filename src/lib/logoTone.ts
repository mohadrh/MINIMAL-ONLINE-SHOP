/**
 * نشان‌هایی که فقط با مرکبِ تیره کشیده شده‌اند.
 *
 * ⚠ فهرست دستی است، و دلیلش این است که از روی خودِ فایل نمی‌شود
 * فهمید.
 *
 * بیشترِ نشان‌های «سیاه‌وسفید» در واقع یک مربعِ سیاه با علامتِ
 * سفید داخلش‌اند — اوپن‌ای‌آی، گراک، میدجرنی، کلاد. آن‌ها روی
 * زمینه‌ی تیره مربعشان را از دست می‌دهند ولی علامتِ سفید می‌ماند
 * و خوانا هستند، پس نباید دست بخورند.
 *
 * این سه‌تا فرق دارند: کلِ نشان یک شکلِ تیره است و هیچ سفیدی در
 * آن نیست. روی زمینه‌ی تیره چیزی از آن‌ها باقی نمی‌ماند.
 *
 * خواندنِ خودکارِ SVG و شمردنِ رنگ‌ها هم جواب نمی‌داد: رنگ‌ها
 * گاهی در ‎<defs>‎ و گرادیانت‌اند و گاهی ‎currentColor‎. سه اسم
 * در یک آرایه، صادقانه‌تر از حدسِ خودکار است.
 */
const MONO_DARK = ['apple', 'capcut', 'x'];

/** آیا این نشان در زمینه‌ی تیره باید به سفید برگردد؟ */
export const isMonoDarkLogo = (src?: string | null) => {
  if (!src) return false;
  const name = src.split('/').pop()?.replace(/\.svg$/i, '') ?? '';
  return MONO_DARK.includes(name);
};
