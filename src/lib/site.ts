/* پیش‌فرض دامنه‌ی خودمان است. بیلدِ گیت‌هاب متغیر را عوض می‌کند. */
const ORIGIN = (process.env.NEXT_PUBLIC_SITE_URL ?? 'https://phonixmarket.com')
  .replace(/\/+$/, '');

/* روی گیت‌هاب سایت زیرِ ‎/MINIMAL-ONLINE-SHOP‎ است و باید در
   آدرس‌های نقشه هم بیاید، وگرنه هر مدخلِ نقشه ۴۰۴ می‌دهد. */
const BASE = (process.env.NEXT_PUBLIC_BASE_PATH ?? '').replace(/\/+$/, '');

/** ریشه‌ی سایت، بدون اسلشِ آخر. */
export const SITE_URL = `${ORIGIN}${BASE}`;

/** یک مسیرِ داخلی را به نشانیِ کامل تبدیل می‌کند. */
export const absolute = (path: string) =>
  `${SITE_URL}/${path.replace(/^\/+/, '')}`;
