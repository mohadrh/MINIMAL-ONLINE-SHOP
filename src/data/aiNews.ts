/* ============================================================
   خبرهای هوش مصنوعی

   ⚠ این فهرست عمداً خالی است.

   کارفرما گفت خبرها را خودش می‌دهد — متن، تصویر و لینکِ ویدیوی
   اینستاگرام. تا آن روز چیزی این‌جا نوشته نمی‌شود.

   خبرِ ساختگی روی فروشگاه ادعایی است که پشتش نیستیم، و خبرِ
   کهنه از نبودِ خبر بدتر است: کاربری که تاریخِ سه‌ماه‌پیش را
   می‌بیند نتیجه می‌گیرد سایت رها شده.

   سکشن هم همین را می‌فهمد: تا وقتی این آرایه خالی باشد اصلاً
   رندر نمی‌شود. یک خبر که اضافه شود، خودش ظاهر می‌شود.

   ⚠ tool باید شناسه‌ی یکی از AI_TOOLS باشد.

   رنگ و نشانِ کارت از همان‌جا می‌آید، پس نامِ اشتباه یعنی کارتِ
   بی‌نشان. بررسی‌اش در حالت توسعه انجام می‌شود.
   ============================================================ */

export interface AiNewsItem {
  id: string;
  /** شناسه‌ی ابزار در AI_TOOLS — رنگ و نشان از آن‌جا می‌آید */
  tool: string;
  title: string;
  /** تاریخ به فارسی، همان‌طور که نوشته می‌شود */
  date: string;
  /** دو سه خط. بلندترش روی کارت بریده می‌شود. */
  body: string;
  /** نشانی تصویر در public — نبودش کارت را نمی‌شکند */
  image?: string;
  /** لینک بیرونی: ویدیوی اینستاگرام، اعلانِ رسمی، … */
  link?: string;
  linkLabel?: string;
}

export const AI_NEWS: AiNewsItem[] = [];

/** کانالی که «همه‌ی اخبار» به آن می‌رود */
export const NEWS_CHANNEL = 'https://t.me/Ph0enix_Shop';

if (process.env.NODE_ENV !== 'production') {
  import('./aiLatest').then(({ AI_TOOLS }) => {
    const ids = new Set(AI_TOOLS.map((t) => t.id));
    for (const n of AI_NEWS) {
      if (!ids.has(n.tool)) {
        console.warn(`[aiNews] «${n.id}» به ابزارِ ناشناخته‌ی «${n.tool}» اشاره می‌کند`);
      }
    }
  });
}
