/** سازنده‌ی محصول بازی — تکرار را حذف می‌کند */
function game(cfg: {
  id: string;
  slug: string;
  title: string;
  englishTitle: string;
  brand: string;
  art: string;
  accent: string;
  short: string;
  description: string;
  features: string[];
  platforms: string[];
  variants: Product['variants'];
  badges?: Product['badges'];
  tags?: string[];
  rating?: number;
  reviews?: number;
  sales?: number;
  fulfillment?: Product['fulfillment'];
  delivery?: string;
  warranty?: string;
  notes?: string[];
  faq?: { q: string; a: string }[];
}): Product {
  return {
    id: cfg.id,
    slug: cfg.slug,
    title: cfg.title,
    englishTitle: cfg.englishTitle,
    brand: cfg.brand,
    platforms: cfg.platforms,
    category: 'gaming',
    fulfillment: cfg.fulfillment ?? 'stock_account',
    requiredInputs: [],
    deliveryEstimate: cfg.delivery ?? 'در اسرع وقت، توسط سیستم',
    warrantyLabel: cfg.warranty ?? 'گارانتی مادام‌العمر فونیکس',
    variants: cfg.variants,
    media: {
      thumbnail: `/games/${cfg.art}-thumb.webp`,
      cover: `/games/${cfg.art}.webp`,
      cutout: `/games/${cfg.art}.webp`,
      accent: cfg.accent,
    },
    shortDescription: cfg.short,
    description: cfg.description,
    features: cfg.features,
    notes: cfg.notes,
    faq: cfg.faq,
    rating: cfg.rating ?? 4.8,
    reviewsCount: cfg.reviews ?? 0,
    salesCount: cfg.sales ?? 0,
    badges: cfg.badges ?? [],
    /* هر اکانت بازی این سه را دارد؛ به‌جای تکرار در هفده جا، همین‌جا
       اضافه می‌شوند و بقیه‌ی برچسب‌ها اختصاصی هر بازی می‌مانند. */
    tags: Array.from(new Set(['capacity', 'private-account', 'instant', ...(cfg.tags ?? [])])),
  };
}

