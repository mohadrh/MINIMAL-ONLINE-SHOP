function toman(usd: number) {
  /* گرد به ده‌هزار تومان — قیمتِ با رقمِ خرد در این بازار
     بی‌اعتماد به نظر می‌رسد */
  return Math.round((usd * RATE) / 10_000) * 10_000;
}

function giftProduct(c: GiftCfg): Product {
  const variants: Variant[] = c.amounts.map((usd, i) => ({
    id: `${c.slug}-${usd}`,
    label: `${usd.toLocaleString('fa-IR')} دلاری`,
    price: toman(usd),
    stock: null,
    isDefault: i === 0,
    guide: {
      fit:
        usd <= 10 ? 'کمترین مبلغ — برای امتحان کردن یا یک خریدِ کوچک.'
        : usd <= 25 ? 'مبلغِ متعارف؛ بیشترِ خریدها همین اندازه است.'
        : usd <= 50 ? 'برای وقتی چند خرید پشت سر هم داری.'
        : 'بیشترین مبلغ — برای شارژِ یک‌باره و طولانی‌مدت.',
      detail:
        `کدِ ${usd.toLocaleString('fa-IR')} دلاری. اعتبار همان مقدار به حسابت اضافه می‌شود و `
        + 'تاریخ انقضا ندارد، پس لازم نیست همان روز خرجش کنی.',
    },
  }));

  return {
    id: c.slug,
    slug: c.slug,
    title: c.title,
    englishTitle: c.english,
    brand: c.brand,
    category: 'giftcard',
    fulfillment: 'stock_code',
    /* گیفت کارت هیچ اطلاعاتی از کاربر نمی‌خواهد — کد تحویل داده
       می‌شود و خودش واردش می‌کند. */
    requiredInputs: [],
    deliveryEstimate: 'در اسرع وقت، توسط سیستم',
    warrantyLabel: 'تضمین سالم بودن کد',
    variants,
    media: { thumbnail: '', accent: c.accent },
    platforms: [c.region],
    shortDescription: c.short,
    description: c.desc,
    features: c.features,
    notes: [
      `ریجن کارت: ${c.region}. ریجن حسابت باید با آن یکی باشد، وگرنه کد وارد نمی‌شود.`,
      'کد پس از تحویل قابل مرجوع کردن نیست — پیش از خرید ریجن حسابت را چک کن.',
    ],
    rating: 4.9,
    reviewsCount: 0,
    salesCount: 0,
    badges: [],
    tags: c.tags,
  };
}

export const GIFT_CARDS: Product[] = CFG.map(giftProduct);

