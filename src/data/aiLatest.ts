/* ============================================================
   تازه‌های هوش مصنوعی

   ⚠ این فهرست جای کاتالوگ را نمی‌گیرد.

   کاتالوگ می‌گوید «چه می‌فروشیم و چند»؛ این‌جا می‌گوید «کدام
   ابزار به چه دردی می‌خورد». کسی که تازه با این حوزه آشنا شده
   نامِ ده سرویس را می‌شنود و نمی‌داند کدامش کارِ او را راه
   می‌اندازد — و تا وقتی نداند، قیمت هم برایش بی‌معنی است.

   پس ترتیب از **کار** می‌آید نه از برند: اول می‌پرسیم می‌خواهی
   بنویسی یا تصویر بسازی یا کد بزنی، بعد ابزارها را نشان می‌دهیم.

   ⚠ هرچه اسلاگ دارد باید در کاتالوگ باشد.

   ابزارهایی که هنوز نمی‌فروشیم اسلاگ ندارند و به‌جای قیمت
   «به‌زودی» می‌گیرند. حدس زدنِ قیمت بدترین کاری است که می‌شود
   کرد: مشتری روی عددی سفارش می‌دهد که ما پشتش نیستیم.
   ============================================================ */

export type AiPurpose = 'chat' | 'visual' | 'code';

export interface AiTool {
  id: string;
  /** نام فارسی — همان که مشتری می‌گوید */
  title: string;
  /** نام لاتین، همان‌طور که خودشان می‌نویسند */
  englishTitle: string;
  /** سازنده */
  maker: string;
  purpose: AiPurpose;
  /** یک جمله: این ابزار چه کاری را راه می‌اندازد */
  lead: string;
  /** دو یا سه کارِ مشخص — نه صفت، فعل */
  does: string[];
  /**
   * نامِ فایلِ نشان در ‎public/brand/logos‎، با پسوند.
   * نبودش کارت را نمی‌شکند؛ حرفِ اول جایش می‌نشیند.
   */
  logo?: string;
  /** رنگِ برند — نوارِ بالای کارت از همین ساخته می‌شود */
  tint: string;
  /** اسلاگِ محصول در کاتالوگ. نبودنش یعنی هنوز نمی‌فروشیم. */
  slug?: string;
  /** تازه اضافه شده — نشانِ گوشه می‌گیرد */
  fresh?: boolean;
  /**
   * نامِ مدلِ فعلیِ سرویس — همان که روی کارت دیده می‌شود.
   *
   * ⚠ فقط مدلی که همین حالا در دسترس است.
   *
   * کارفرما «مدل فلان در راه است» می‌خواست. مدلی که هنوز نیامده
   * را نمی‌نویسیم: تاریخِ عرضه دستِ ما نیست و اگر عقب بیفتد،
   * سایت وعده‌ای داده که خودش نمی‌تواند نگه دارد. نامِ مدلِ
   * موجود همان کار را می‌کند و راست هم هست.
   *
   * وقتی مدلِ تازه‌ای آمد، همین یک رشته عوض می‌شود.
   */
  model?: string;

  /* ---------- محتوای پنجره‌ی جزئیات ---------- */

  /** مدل‌ها یا پلن‌های همین سرویس، با یک خط توضیح */
  models?: { name: string; note: string }[];
  /**
   * کارهای مشخصی که می‌شود باهاش کرد — بلندتر از does و با مثال.
   * does روی کارت است و باید کوتاه بماند؛ این‌جا جا هست.
   */
  uses?: { title: string; body: string }[];
  /**
   * خبرها. کارفرما پر می‌کند.
   *
   * ⚠ خالی گذاشتنش عمدی است. خبرِ ساختگی روی سایت فروشگاه یعنی
   * ادعایی که پشتش نیستیم؛ و خبرِ کهنه از نبودِ خبر بدتر است.
   * تا وقتی متن و تصویر و لینک نرسیده، این بخش در پنجره اصلاً
   * نشان داده نمی‌شود.
   */
  news?: {
    title: string;
    /** تاریخ به فارسی، همان‌طور که نوشته می‌شود */
    date: string;
    body: string;
    /** نشانی تصویر در public — نبودش خبر را نمی‌شکند */
    image?: string;
    /** لینک بیرونی: ویدیوی اینستاگرام، اعلانِ رسمی، … */
    link?: string;
    linkLabel?: string;
  }[];
}

