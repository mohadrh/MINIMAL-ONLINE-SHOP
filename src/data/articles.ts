/* ============================================================
   ساختِ فهرستِ نهایی

   ⚠ سه فیلد از ورودی *گرفته نمی‌شوند*، حساب می‌شوند:
   زمانِ مطالعه، برچسبِ موضوع، و رنگ.

   زمانِ مطالعه چون نویسنده حدسش را می‌زند و بد می‌زند — چهار
   مقاله‌ی قبلی هفت تا یازده دقیقه ادعا می‌کردند و واقعاً یک تا
   دو دقیقه بودند. روی سایتی که حرفش اعتماد است، این عدد نباید
   دروغ بگوید.

   برچسب و رنگ چون دو مقاله‌ی هم‌موضوع باید شبیهِ هم دیده شوند،
   و وقتی هر مقاله خودش می‌نوشتشان، نمی‌شدند.
   ============================================================ */

/** آنچه نویسنده می‌نویسد — بقیه‌اش حساب می‌شود */
export type ArticleInput =
  Omit<Article, 'readMinutes' | 'topicLabel' | 'accent'>
  & Partial<Pick<Article, 'topicLabel' | 'accent'>>;

function build(a: ArticleInput): Article {
  const t = TOPICS[a.topic];
  return {
    ...a,
    topicLabel: a.topicLabel ?? t.label,
    accent: a.accent ?? t.accent,
    readMinutes: readingMinutes(a.body),
  };
}

/**
 * نوشتنِ مقاله‌ی تازه.
 *
 * ```ts
 * article({
 *   slug: 'steam-full-vs-shared',
 *   title: '…',
 *   excerpt: '…',
 *   topic: 'gaming',
 *   publishedAt: '۳۰ شهریور ۱۴۰۵',
 *   cover: '/games/battlefield-6-wide.webp',
 *   coverWide: true,
 *   body: [ p('…'), h('…'), ul([…]), product('chatgpt-plus') ],
 * })
 * ```
 */
/* ⚠ ‎function‎ و نه ‎const‎ — چون بالای همین فایل صدا زده
   می‌شود و ‎const‎ بالا نمی‌رود (hoist نمی‌شود). */
export function article(a: ArticleInput): ArticleInput {
  return a;
}

export const ARTICLES: Article[] = RAW.map(build);

export const getArticleBySlug = (slug: string) =>
  ARTICLES.find((a) => a.slug === slug);

/** مقاله‌های مرتبط — هم‌موضوع، بدون خود مقاله */
export const getRelatedArticles = (slug: string, limit = 3) => {
  const current = getArticleBySlug(slug);
  if (!current) return [];
  const sameTopic = ARTICLES.filter((a) => a.slug !== slug && a.topic === current.topic);
  const rest = ARTICLES.filter((a) => a.slug !== slug && a.topic !== current.topic);
  return [...sameTopic, ...rest].slice(0, limit);
};

/* ---------------------------------------------------------------
   مقاله‌های مرتبط با یک محصول.

   دسته‌ی محصول مستقیم به موضوع مقاله نگاشت می‌شود. دو دسته‌ای که
   موضوع اختصاصی ندارند — شبکه‌های اجتماعی و آموزش — به «راهنما»
   می‌روند، چون مقاله‌های آن‌جا عمومی‌اند و به هر خریدی می‌خورند.

   اگر هم‌موضوع کم بود، با راهنماها پر می‌شود: بهتر است کاربر سه
   مقاله‌ی کمی مرتبط ببیند تا یک مقاله و دو جای خالی.
--------------------------------------------------------------- */
const CATEGORY_TOPIC: Record<string, ArticleTopic> = {
  ai: 'ai',
  gaming: 'gaming',
  creative: 'creative',
  social: 'guide',
  education: 'guide',
};

export const getArticlesForCategory = (category: string, limit = 3): Article[] => {
  const topic = CATEGORY_TOPIC[category] ?? 'guide';
  const onTopic = ARTICLES.filter((a) => a.topic === topic);
  const guides = ARTICLES.filter((a) => a.topic === 'guide' && a.topic !== topic);
  return [...onTopic, ...guides].slice(0, limit);
};
