export const getArticleBySlug = (slug: string) =>
  ARTICLES.find((a) => a.slug === slug);

/** مقاله‌های مرتبط — هم‌موضوع، بدون خود مقاله */
export const getRelatedArticles = (slug: string, limit = 3) => {
  const current = getArticleBySlug(slug);
  if (!current) return [];
  const sameTopic = ARTICLES.filter((a) => a.slug !== slug && a.topic === current.topic);
  const rest = ARTICLES.filter((a) => a.slug !== slug && a.topic !== current.topic);
  return [...sameTopic, ...rest].slice(0, limit);
};
