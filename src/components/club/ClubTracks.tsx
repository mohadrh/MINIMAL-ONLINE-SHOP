'use client';

import React, { useEffect, useState } from 'react';

/**
 * مسیرهای باشگاه.
 *
 * پس‌زمینه‌ی صفحه‌ی باشگاه: شبکه‌ای از لوله‌های محو که گلوله‌های
 * نورانی در آن‌ها راه می‌روند، مثل کارخانه‌ای که پشت شیشه می‌بینی.
 * قرار است حسِ «یک سیستمی این پشت کار می‌کند» بدهد — چون واقعاً
 * همین است: امتیاز جمع می‌شود، پله بالا می‌رود، کش‌بک برمی‌گردد.
 *
 * سه تصمیم:
 *
 * ۱. الگو سه بار عمودی تکرار می‌شود.
 *
 *    یک قابِ ۱۲۰۰×۸۰۰ روی صفحه‌ای که سه هزار پیکسل بلند است، با
 *    slice نزدیک چهار برابر بزرگ می‌شد و شبکه به سه خطِ غول‌پیکر
 *    تبدیل — نه شبکه‌ای که بشود دنبالش کرد. با سه نوارِ پشت سر هم،
 *    قاب ۱۲۰۰×۲۴۰۰ می‌شود و مقیاس نزدیک یک می‌ماند.
 *
 * ۲. حرکت با offset-path در CSS است، نه با animateMotion.
 *    نسخه‌ی اول SMIL بود و در کروم اصلاً تکان نمی‌خورد: <mpath>
 *    در کروم فقط xlink:href را می‌خواند و href ساده را نادیده
 *    می‌گیرد — انیمیشن ساخته می‌شد، getStartTime هم جواب می‌داد،
 *    ولی گلوله سر جایش می‌ماند. offset-path این ابهام را ندارد و
 *    مسیر همان رشته‌ای است که خودِ لوله با آن کشیده شده، پس
 *    هیچ‌وقت از هم نمی‌افتند.
 *
 * ۳. اگر کاربر حرکت کمتر خواسته باشد، اصلاً رندر نمی‌شود — نه
 *    اینکه رندر شود و متوقف بماند. پس‌زمینه‌ی تزئینی که حرکت
 *    نمی‌کند، فقط شلوغی است.
 */

/* مسیرها عمداً گوشه‌دارِ گردند نه منحنیِ آزاد: باید شبیه لوله‌کشی
   یا مدار دیده شوند، نه شبیه دود. */
const TRACKS = [
  'M -60 120 H 250 Q 300 120 300 170 V 380 Q 300 430 350 430 H 700 Q 750 430 750 380 V 190 Q 750 140 800 140 H 1260',
  'M -60 640 H 180 Q 230 640 230 590 V 300 Q 230 250 280 250 H 560 Q 610 250 610 300 V 620 Q 610 670 660 670 H 1260',
  'M -60 380 H 120 Q 170 380 170 430 V 700 Q 170 750 220 750 H 880 Q 930 750 930 700 V 480 Q 930 430 980 430 H 1260',
  'M -60 220 H 420 Q 470 220 470 170 V 90  Q 470 40  520 40  H 980 Q 1030 40 1030 90 V 300 Q 1030 350 1080 350 H 1260',
];

/* هر گلوله: مسیر، تأخیر، مدت، رنگ. رنگ‌ها از کمان ققنوس‌اند تا
   پس‌زمینه با بقیه‌ی سایت یک زبان داشته باشد. */
const PELLETS = [
  { t: 0, delay: 0,    dur: 18, c: '#f59440', r: 4 },
  { t: 0, delay: 7,    dur: 18, c: '#ff4d9f', r: 3 },
  { t: 1, delay: 2.5,  dur: 22, c: '#3ddcff', r: 4 },
  { t: 1, delay: 12,   dur: 22, c: '#c94ff5', r: 3 },
  { t: 2, delay: 5,    dur: 26, c: '#f5b942', r: 4 },
  { t: 2, delay: 16,   dur: 26, c: '#4ade80', r: 3 },
  { t: 3, delay: 1,    dur: 20, c: '#7a6bff', r: 4 },
  { t: 3, delay: 10.5, dur: 20, c: '#ff7a45', r: 3 },
];

/* گره‌ها — جایی که مسیرها می‌پیچند. نقطه‌هایی که آرام نفس می‌کشند
   و به شبکه حس «زنده» می‌دهند بدون اینکه چیزی جابه‌جا شود. */
const NODES = [
  [300, 170], [350, 430], [750, 380], [800, 140],
  [230, 590], [280, 250], [610, 300], [660, 670],
  [170, 430], [220, 750], [930, 700], [980, 430],
  [470, 170], [520, 40],  [1030, 90], [1080, 350],
];

export function ClubTracks() {
  const [on, setOn] = useState(false);

  useEffect(() => {
    setOn(!window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  }, []);

  if (!on) return null;

  return (
    <div className="ctracks" aria-hidden="true">
      <svg viewBox="0 0 1200 2400" preserveAspectRatio="xMidYMid slice">
        <defs>
          {/* هاله‌ی گلوله‌ها. بدون آن، نقطه‌ها تخت‌اند و شبیه گَرد
              دیده می‌شوند نه چیزی که در لوله حرکت می‌کند. */}
          <filter id="ctglow" x="-200%" y="-200%" width="500%" height="500%">
            <feGaussianBlur stdDeviation="4" result="b" />
            <feMerge>
              <feMergeNode in="b" />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>
        </defs>

        {/* سه نوار، هر کدام ۸۰۰ واحد.

            نوارِ وسط عمداً آینه‌ی افقی است تا تکرار به چشم نیاید؛
            بدون آن، سه بارِ یکسان زیر هم مثل کاغذدیواری دیده
            می‌شود نه مثل یک شبکه. */}
        {[0, 800, 1600].map((y, band) => (
          <g key={y} transform={band === 1 ? `translate(1200 ${y}) scale(-1 1)` : `translate(0 ${y})`}>
            <g className="ctracks__pipe">
              {TRACKS.map((d, i) => <path key={i} d={d} />)}
            </g>

            <g className="ctracks__node">
              {NODES.map(([x, ny], i) => (
                <circle
                  key={i}
                  cx={x}
                  cy={ny}
                  r="3"
                  style={{ animationDelay: `${((i + band * 2) % 6) * 0.7}s` }}
                />
              ))}
            </g>

            <g filter="url(#ctglow)">
              {PELLETS.map((p, i) => (
                <circle
                  key={i}
                  className="ctracks__pellet"
                  r={p.r}
                  fill={p.c}
                  style={{
                    offsetPath: `path("${TRACKS[p.t]}")`,
                    animationDuration: `${p.dur + band * 3}s`,
                    animationDelay: `-${p.delay + band * 4}s`,
                  }}
                />
              ))}
            </g>
          </g>
        ))}
      </svg>
    </div>
  );
}
