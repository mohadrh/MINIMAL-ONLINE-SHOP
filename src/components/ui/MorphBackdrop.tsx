import React from 'react';

/**
 * پس‌زمینه‌ی هاله‌های متحرک.
 *
 * نسخه‌ی اول یک مسیر SVG هم داشت که وسط قاب مورف می‌شد. آن را
 * برداشتم: روی یک باکسِ پهن، آن شکل فقط یک دایره‌ی مات وسط صفحه
 * می‌شد و به‌جای پس‌زمینه، شبیه یک المانِ فراموش‌شده بود. چیزی که
 * کار می‌کند هاله‌هاست، نه شکلِ مشخص.
 *
 * هر هاله یک گرادیانت مخروطی است که هم‌زمان دو کار می‌کند: شکلش با
 * border-radius هشت‌مقداری عوض می‌شود و خودش هم می‌چرخد. چون
 * گرادیانت مخروطی است، چرخیدنش رنگ را هم می‌چرخاند — رنگِ توپر این
 * را نمی‌دهد و فقط یک لکه‌ی مات می‌ماند.
 *
 * دوره‌ی چرخش ۲٫۳ برابر دوره‌ی مورف است تا دو حرکت روی هم قفل
 * نشوند؛ اگر هم‌دوره باشند، هاله ضرب‌آهنگ پیدا می‌کند و مصنوعی
 * دیده می‌شود.
 */

type Tone = 'blue' | 'warm';

/* ⚠ فام‌ها از چهار رنگِ خودِ تم می‌آیند، نه از سلیقه.

   قبلاً ۲۳۲ و ۲۰۸ و ۲۶۲ و ۱۹۰ بودند — چهار آبی و بنفشِ دلخواه که
   به پالتِ بنفشِ قدیمی می‌خوردند. کنارِ تراکوتا سرد و بیگانه
   می‌نشستند و کارفرما گفت گرادیانت شبیهِ تم شود.

   حالا هر هاله فامِ یکی از چهار خانواده‌ی پالت است:

     ۲۰۹  آبیِ اعتماد   #185fa5
     ۱۷   تراکوتای برند #c24a24
     ۲۴۶  بنفشِ هوش مصنوعی #534ab7
     ۳۳   کهربایی باشگاه  #854f0b

   یعنی همان چهار رنگی که در کلِ سایت کار می‌کنند، این‌جا هم
   پشتِ سکشن می‌چرخند. */
const SETS: Record<Tone, { t: string; x: string; y: string; s: string; h: number }[]> = {
  blue: [
    { t: '13s', x: '12%', y: '18%', s: '42%', h: 209 },
    { t: '17s', x: '72%', y: '26%', s: '34%', h: 17 },
    { t: '15s', x: '54%', y: '78%', s: '46%', h: 246 },
    { t: '19s', x: '22%', y: '82%', s: '30%', h: 33 },
  ],
  warm: [
    { t: '14s', x: '16%', y: '22%', s: '40%', h: 17 },
    { t: '18s', x: '76%', y: '20%', s: '32%', h: 33 },
    { t: '16s', x: '52%', y: '80%', s: '44%', h: 246 },
    { t: '20s', x: '86%', y: '72%', s: '28%', h: 209 },
  ],
};

export function MorphBackdrop({
  tone = 'blue',
  className = '',
}: {
  tone?: Tone;
  className?: string;
}) {
  return (
    <div
      className={`absolute inset-0 -z-10 overflow-hidden ${className}`}
      aria-hidden="true"
    >
      {/* شست‌وشوی پایه — هاله‌ها روی چیزی بنشینند، نه روی خلأ */}
      <div
        className="absolute inset-0"
        style={{
          /* ⚠ از توکن می‌آید، نه hex.

             ‎#e7edfb‎ یک سفیدِ آبی‌مایل بود از پالتِ قبلی و روی
             کرمِ تازه مثل یک لکه‌ی سردِ چسبانده دیده می‌شد. حالا
             از کارتِ سفید به کرمِ صفحه می‌رود — یعنی دقیقاً همان
             دو سطحی که بقیه‌ی صفحه هم از آن‌ها ساخته شده. */
          background:
            tone === 'blue'
              ? 'radial-gradient(120% 100% at 50% 0%, var(--paper), var(--page) 82%)'
              : 'radial-gradient(120% 100% at 50% 0%, var(--paper), var(--brand-wash) 82%)',
        }}
      />

      {/* هاله‌ها.

          بلور بالا و اشباع کمی بیشتر: بدون بلور، لبه‌ی شکلِ مورف
          دیده می‌شود و به‌جای هاله یک لکه‌ی کش‌دار به نظر می‌رسد. */}
      <div className="absolute inset-0 opacity-70 blur-[40px] saturate-125">
        {SETS[tone].map((b) => (
          <span
            key={`${b.x}-${b.y}`}
            /* انیمیشن با کلاس CSS نوشته می‌شود نه با مقدار دلخواهِ
               تیلویند: سه انیمیشنِ هم‌زمان با کاما داخل
               animate-[...] خوانا نیست و به‌راحتی می‌شکند. */
            className="morphblob absolute aspect-square mix-blend-multiply"
            style={{
              ['--t' as string]: b.t,
              left: b.x,
              top: b.y,
              width: b.s,
              translate: '-50% -50%',
              background: `conic-gradient(from 140deg,
                hsl(${b.h} 74% 74%),
                hsl(${b.h + 40} 68% 82%),
                hsl(${b.h - 30} 80% 70%),
                hsl(${b.h} 74% 74%))`,
            }}
          />
        ))}
      </div>
    </div>
  );
}
