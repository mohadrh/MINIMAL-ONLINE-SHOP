import React from 'react';
import { ServiceMark } from '../numbers/ServiceMark';

/**
 * تصویرِ اسلایدر هیرو.
 *
 * جای PNG را گرفت. تصویرهای قبلی همان چیدمان را داشتند — یک کارتِ
 * رنگی، دو خط متنِ محو، سه درخشش، و چهار کاشی — ولی روی کاشی‌ها
 * فقط **حرف اولِ** نام سرویس نوشته بود: «C» برای کلاد، «G» برای
 * جمینای، «P» برای پلی‌استیشن.
 *
 * کارفرما همین را رد کرد و درست هم بود: آدم سرویس را از روی شکلش
 * می‌شناسد نه از روی حرف اولش، و حرفِ تنها شبیهِ کارِ نیمه‌تمام
 * است. حالا همان کاشی‌ها نشانِ واقعی را نشان می‌دهند.
 *
 * ⚠ اشتباهِ قبلی را تکرار نمی‌کنیم: یک بار نشان‌ها را به‌صورت
 * کاشی‌های شیشه‌ای **روی** بنر گذاشتیم و کارفرما گفت «این سه تا
 * باکسی که گذاشتی روی همه اسلایدها رو نمی‌فهمم برش دار». نشان
 * جعبه‌ی اضافه نمی‌خواهد؛ این‌جا کاشی‌ها خودِ تصویرند، نه چیزی که
 * رویش سوار شده باشد.
 *
 * چرا HTML و نه یک SVG یک‌پارچه: نشان‌ها کامپوننت‌اند و با
 * currentColor رنگ می‌گیرند. با HTML مستقیم همان‌ها را می‌گذاریم
 * وسط کاشی؛ با SVGِ تودرتو باید هرکدام دوباره تعریف می‌شد.
 *
 * اندازه‌ها درصدی‌اند و متن با واحد cqw مقیاس می‌گیرد، پس تصویر در
 * هر عرضی همان نسبت را نگه می‌دارد — کاری که PNG با یک اندازه‌ی
 * ثابت نمی‌کرد.
 */

export interface SlideArtSpec {
  /** رنگ کارتِ پس‌زمینه */
  card: string;
  /** دو خط متنِ محو روی کارت */
  label: [string, string];
  /**
   * چهار کاشی، **به ترتیبِ رسم** — از عقب به جلو.
   *
   * ترتیب مهم است چون کاشی‌ها روی هم می‌افتند: چپ، بالا، پایین،
   * راست. همان ترتیبی که تصویرهای اصلی داشتند.
   */
  tiles: { id: string; bg: string; ink?: string }[];
}

/* جای چهار کاشی، بر حسب درصدِ عرض و ارتفاعِ تصویر (۱۲۰۰×۷۶۰).

   از روی همان تصویرهای اصلی اندازه گرفته شده تا چیدمان عوض نشود؛
   فقط محتوای کاشی‌ها فرق می‌کند. */
const SLOTS = [
  { left: 3.33, top: 40.79 },
  { left: 11.08, top: 26.05 },
  { left: 15.0, top: 51.58 },
  { left: 26.5, top: 42.76 },
];

/* درخشش‌ها — همان سه نقطه‌ی تصویر اصلی */
const SPARKS = [
  { left: 34.83, top: 33.95, size: 2.0 },
  { left: 51.0, top: 30.53, size: 1.5 },
  { left: 22.67, top: 71.32, size: 2.3 },
];

export function SlideArt({ spec }: { spec: SlideArtSpec }) {
  return (
    <div className="slart" aria-hidden="true">
      {/* کارت */}
      <span className="slart__card" style={{ background: spec.card }} />

      {/* متنِ محو روی کارت */}
      <span className="slart__label">
        <b>{spec.label[0]}</b>
        <b>{spec.label[1]}</b>
      </span>

      {SPARKS.map((s, i) => (
        <span
          key={i}
          className="slart__spark"
          style={{
            left: `${s.left}%`,
            top: `${s.top}%`,
            ['--s' as string]: `${s.size}cqw`,
          }}
        />
      ))}

      {spec.tiles.slice(0, 4).map((t, i) => (
        <span
          key={t.id}
          className="slart__tile"
          style={{
            left: `${SLOTS[i].left}%`,
            top: `${SLOTS[i].top}%`,
            background: t.bg,
            color: t.ink ?? '#fff',
          }}
        >
          <ServiceMark id={t.id} mark={t.id.slice(0, 1).toUpperCase()} />
        </span>
      ))}
    </div>
  );
}
