#!/usr/bin/env node
/* ============================================================
   نگهبانِ لحن

       npm run lint:copy

   ⚠ چرا این وجود دارد

   کارفرما روی «سه سوالی که بیشتر می‌پرسند» دست گذاشت و گفت لحنش
   ماشینی است. حق داشت، و مهم‌تر اینکه آن یکی تنها نبود — «سه
   قدم»، «چهار پله»، «چهار راه»، «سه پله»، «چهار مدل، چهار
   کاربرد». یک الگو بود نه یک اشتباه.

   الگو این است: **شمردنِ چیزی که همان‌جا پیداست.** آدم وقتی تیتر
   می‌نویسد آیتم‌ها را برایت نمی‌شمارد؛ خودشان زیرِ تیتر هستند.
   شمردن، کارِ کسی است که دارد ساختار را توضیح می‌دهد نه حرف
   می‌زند.

   این اسکریپت همان الگوها را می‌گیرد تا دفعه‌ی بعد کسی — من یا
   هر کس دیگر — دوباره ننویسدشان.

   ⚠ این ابزار سلیقه نیست، فهرست است. اگر جایی واقعاً لازم بود
   عدد بیاید، در ALLOW اضافه‌اش کن و دلیلش را بنویس.
   ============================================================ */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');

/* ---------------------------------------------------------------
   الگوها
--------------------------------------------------------------- */

const NUM = '(یک|دو|سه|چهار|پنج|شش|هفت|هشت|نه|ده)';

const RULES = [
  {
    id: 'شمردن در تیتر',
    re: new RegExp(`<h[1-3]>\\s*${NUM}\\s+\\S+`),
    why: 'تیتر آیتم‌ها را نمی‌شمارد؛ خودشان زیرش هستند.',
    fix: 'عدد را بردار: «سه قدم» → «چطور کار می‌کند»',
  },
  {
    id: 'شمردن در برچسب بالای تیتر',
    re: new RegExp(`sec-head__kicker">\\s*${NUM}\\s+\\S+\\s*<`),
    why: 'همان مشکل، یک خط بالاتر.',
    fix: '«چهار پله» → «پله‌ها»',
  },
  {
    id: 'تکرار قرینه',
    /* ⚠ فقط در تیتر، برچسب و لید.

       نسخه‌ی اول همه‌جا می‌گشت و فهرست‌های واقعی را هم می‌گرفت:
       «یک قرارداد، یک پایان‌نامه، یک پروژه» در متنِ مقاله برشمردنِ
       مثال است نه تقارنِ ساختگی. تفاوتشان جای وقوع است — تیتر
       ادعا می‌کند، متنِ مقاله توضیح می‌دهد. */
    re: new RegExp(
      `(<h[1-3]>|kicker">|lead">|kicker:\\s*')[^<']*${NUM}\\s+\\S+،\\s*${NUM}\\s`,
    ),
    why: '«چهار مدل، چهار کاربرد» — تقارنِ ساختگی، نشانه‌ی متنِ تولیدشده.',
    fix: 'یک جمله‌ی ساده بنویس: «هر کدام برای کار متفاوتی ساخته شده.»',
  },
  {
    id: 'عبارت پرکننده',
    re: /(در یک نگاه|هر آنچه باید بدانید|همه چیز درباره|به طور کلی|شایان ذکر است|لازم به ذکر)/,
    why: 'عبارتی که چیزی به جمله اضافه نمی‌کند.',
    fix: 'حذفش کن؛ جمله بدون آن کامل است.',
  },
  {
    id: 'وعده‌ی مطلق',
    re: /(تضمین (صد در صد|۱۰۰|100)|هرگز مسدود نمی|بدون هیچ (گونه )?(مشکل|ریسک))/,
    why: 'وعده‌ای که نمی‌توانیم پایش بایستیم.',
    fix: 'بگو واقعاً چه کاری می‌کنیم، نه اینکه چه چیزی هرگز پیش نمی‌آید.',
  },
];

/* چیزهایی که عدد در آن‌ها درست است */
const ALLOW = [
  // شماره‌ی مجازی واقعاً از «بیش از سی کشور» است — عدد اطلاعات است
  'بیش از سی کشور',
  // «دو فیلد، و تمام» لحن دارد و ادعا نیست
  'دو فیلد، و تمام',
  // «هر سه راه به یک تیم می‌رسد» جمله‌ی واقعی است نه تیتر
  'هر سه راه',
  /* «سه ابزار، یک بار پرداخت» الگوی قرینه دارد ولی اطلاعات
     واقعی می‌دهد: بسته‌ی طراحی سه ابزار است و یک بار پول
     می‌دهی. قاعده اینجا درست شلیک می‌کند ولی مشکلی نیست —
     تفاوتِ «تقارنِ توخالی» و «واقعیتِ قرینه». */
  'سه ابزار، یک بار پرداخت',
];

/* ---------------------------------------------------------------
   پویش
--------------------------------------------------------------- */

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(name)) out.push(p);
  }
  return out;
}

/**
 * کامنت‌ها بررسی نمی‌شوند — آن‌ها برای برنامه‌نویس‌اند نه کاربر.
 *
 * ⚠ به‌جای حذف، خطِ خالی می‌گذاریم.
 *
 * نسخه‌ی اول کامنت را با یک فاصله عوض می‌کرد و شماره‌ی خط‌ها
 * جابه‌جا می‌شد: گزارش به خطی اشاره می‌کرد که چیز دیگری در آن
 * بود. لینتری که آدرس غلط بدهد از نبودنش بدتر است.
 */
function stripComments(s) {
  const KEEP_NEWLINE = /[^\n]/g;
  return s
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(KEEP_NEWLINE, ' '))
    .replace(/^(\s*)\/\/.*$/gm, '$1');
}

const findings = [];

for (const file of walk(SRC)) {
  const raw = readFileSync(file, 'utf8');
  const body = stripComments(raw);

  body.split('\n').forEach((line, i) => {
    if (ALLOW.some((a) => line.includes(a))) return;

    for (const rule of RULES) {
      const m = rule.re.exec(line);
      if (m) {
        findings.push({
          file: relative(ROOT, file).replace(/\\/g, '/'),
          line: i + 1,
          rule,
          text: line.trim().slice(0, 88),
        });
      }
    }
  });
}

/* ---------------------------------------------------------------
   گزارش
--------------------------------------------------------------- */

if (findings.length === 0) {
  console.log('\n✓ هیچ متنی الگوی ماشینی ندارد.\n');
  process.exit(0);
}

console.log(`\n${findings.length} مورد پیدا شد:\n`);

let last = '';
for (const f of findings) {
  if (f.rule.id !== last) {
    console.log(`── ${f.rule.id}`);
    console.log(`   ${f.rule.why}`);
    console.log(`   راه‌حل: ${f.rule.fix}\n`);
    last = f.rule.id;
  }
  console.log(`   ${f.file}:${f.line}`);
  console.log(`   ${f.text}\n`);
}

process.exit(1);
